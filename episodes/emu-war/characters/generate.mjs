import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import { CHARACTERS, EXPRESSIONS, POSES, VIEWS, renderCharacter, renderSheet } from './rig.mjs';
const require=createRequire(import.meta.url);
const { chromium }=require('../../../templates/threejs_film/node_modules/playwright');
const out=path.dirname(fileURLToPath(import.meta.url));
const escHtml=s=>s.replaceAll('&','&amp;').replaceAll('"','&quot;');
await fs.mkdir(out,{recursive:true});
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:2160,height:2160}, deviceScaleFactor:1});
async function png(svg,file){
  const html=`<html><body style="margin:0;background:#101722"><img id="x" src="data:image/svg+xml;base64,${Buffer.from(svg).toString('base64')}"/></body></html>`;
  await page.setContent(html); await page.locator('#x').screenshot({path:path.join(out,file)});
}
for(const spec of Object.values(CHARACTERS)){
  const turn=renderSheet(spec,VIEWS.map(v=>renderCharacter(spec,v,'determined','idle')),`${spec.label} · TURNAROUND`,5);
  await png(turn,`${spec.id}_turnaround.png`);
  const expr=renderSheet(spec,EXPRESSIONS.map(e=>renderCharacter(spec,'front',e,'idle')),`${spec.label} · EXPRESSIONS`,4,420,720);
  await png(expr,`${spec.id}_expressions.png`);
  const poses=renderSheet(spec,POSES.map(p=>renderCharacter(spec,p==='run'?'three-quarter-right':'front','determined',p)),`${spec.label} · POSES`,4,420,720);
  await png(poses,`${spec.id}_poses.png`);
  const frames=[];
  for(let i=0;i<8;i++) frames.push(renderCharacter(spec,'three-quarter-right',i%4===0?'determined':i%4===2?'worried':'determined',`walk${i}`,420,720).replace('</svg>',`<text x="20" y="70" fill="#fff" font-size="18">walk frame ${i+1}/8</text></svg>`));
  await fs.writeFile(path.join(out,`${spec.id}_walk_frames.svg`),frames.join('\n'));
}
await fs.writeFile(path.join(out,'README.md'),`# Procedural Emu War characters\n\nGenerated by \`generate.mjs\` from \`rig.mjs\`. No PNG from the skill kit is imported.\n\nEvery character is a separate layered SVG rig with named parts, pivots, view redraws, expressions and pose presets.\n`);
await browser.close();
console.log(`Generated ${Object.keys(CHARACTERS).length} character families in ${out}`);
